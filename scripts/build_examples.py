"""Write example files for the skills from steerage's data/pairs.jsonl.

Examples are before/after pairs: Claude's first draft and the version I ended
up with. Only public content goes here, never conversation text.

- PR descriptions: agent-drafted bodies I edited.
- Release notes: agent-drafted descriptions changed by a revision commit on the PR.
- Commit messages: merged PR titles and agent revision commit subjects.

My own writing from before the agent era goes in separate files, not mixed
with the pairs: final descriptions of merged PRs, PR titles and revision
commit subjects.

Examples name no people or repos. Logins and names from data/people.tsv, extra
logins listed one per line in scrub.txt (gitignored), and @mentions outside
code become a placeholder, and headings carry only the title.
data/examples.tsv maps each example back to its PR.

Output: claude/skills/*/examples/*.md
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
SKILLS = ROOT / "claude" / "skills"
HEADER = "<!-- Generated by scripts/build_examples.py. Don't edit by hand. -->\n\n"
CHORE = re.compile(r"^(merge|wip|fixup!|squash!|chore|style|lint|format|ruff|fprettify)", re.I)
MAX_BODY = 2500
# underscores aren't allowed in GitHub logins, so this never mentions anyone
PLACEHOLDER = "some_user"
CODE = re.compile(r"(```.*?```|`[^`\n]*`)", re.S)
EMAIL = re.compile(r"[\w.+-]+@[\w-]+(\.[\w-]+)*\.[A-Za-z]{2,}\b")
COAUTHOR = re.compile(r"(?im)^(\s*co-authored-by:).*$")
MENTION = re.compile(r"(?<![\w.`/-])@[A-Za-z0-9][A-Za-z0-9-]*")


def read_jsonl(path):
    with open(path) as f:
        return [json.loads(l) for l in f if l.strip()]


def words(terms, flags=0):
    alts = "|".join(map(re.escape, sorted(terms, key=len, reverse=True)))
    return re.compile(rf"(?<![\w-])({alts})(?![\w-])", flags)


def scrubber(people, corpus):
    """Replace logins, names, emails and co-authors anywhere, and other @mentions outside code.

    Logins and full names match in any case. Single name parts match only as
    written, and not at all if the corpus also uses them in lowercase, since
    then they're common words.
    """
    names = [n for _, n in people if n]
    common = set(re.findall(r"(?<![\w/-])[a-z]+(?![\w/@-])", corpus))
    whole = words([l for l, _ in people] + names, re.I)
    part = words({w for n in names for w in re.findall(r"[^\s,.]{3,}", n) if w.lower() not in common})

    def scrub(text):
        text = COAUTHOR.sub(rf"\1 {PLACEHOLDER}", EMAIL.sub(f"{PLACEHOLDER}@example.com", text))
        parts = CODE.split(part.sub(PLACEHOLDER, whole.sub(PLACEHOLDER, text)))
        parts[::2] = [MENTION.sub("@" + PLACEHOLDER, p) for p in parts[::2]]
        return "".join(parts)

    return scrub


def spread(items, n):
    """n items evenly spaced through a list, so short and long both show up."""
    if len(items) <= n:
        return items
    return [items[round(i * (len(items) - 1) / (n - 1))] for i in range(n)]


def fence(text: str) -> str:
    return "````\n" + text + "\n````\n"


def pr_descriptions(pairs, n=14):
    pairs = [r for r in pairs if r["kind"] == "pr-description" and r["drafter"] == "agent"
             and r["draft"] is not None and max(len(r["draft"]), len(r["final"])) <= MAX_BODY]
    pairs.sort(key=lambda r: len(r["final"]))
    used = spread(pairs, n)
    out = [HEADER, "# PR descriptions: your draft, then mine\n\n",
           "Each pair is a description you wrote and the version I edited it into by hand. "
           "Template checklists are stripped.\n"]
    for r in used:
        out += [f"\n## {r['title']}\n\n", "Draft:\n\n", fence(r["draft"]), "\nMine:\n\n", fence(r["final"])]
    return "".join(out), len(pairs), used


def release_notes(pairs, n=16):
    pairs = [r for r in pairs if r["kind"] == "release-note" and r["drafter"] == "agent"]
    pairs.sort(key=lambda r: len(r["final"]))
    used = spread(pairs, n)
    out = [HEADER, "# Release notes: your draft, then mine\n\n",
           "Each pair is the first release note description on a PR and the final one after my revisions.\n"]
    for r in used:
        out += [f"\n## {r['path'].rsplit('/', 1)[-1]}\n\n",
                "Draft:\n\n", "> " + r["draft"] + "\n", "\nMine:\n\n", "> " + r["final"] + "\n"]
    return "".join(out), len(pairs), used


def own_descriptions(pairs, n=24):
    pairs = [r for r in pairs if r["kind"] == "pr-description" and r["merged"]
             and not CHORE.match(r["title"]) and len(r["final"]) <= MAX_BODY]
    pairs.sort(key=lambda r: len(r["final"]))
    used = spread(pairs, n)
    out = [HEADER, "# PR descriptions I wrote before using agents\n\n",
           "Final descriptions of merged PRs, written by me alone. Template checklists are stripped.\n"]
    for r in used:
        out += [f"\n## {r['title']}\n\n", fence(r["final"])]
    return "".join(out), len(pairs), used


def commit_messages(pairs, n_titles=30, n_revs=40, drafter="agent", title="Commit messages"):
    titles = [r for r in pairs if r["kind"] == "pr-title" and r["merged"] and not CHORE.match(r["final"])]
    titles.sort(key=lambda r: r["created"])
    revs, seen = [], set()
    for r in pairs:
        subj = r["final"]
        if (r["kind"] == "commit-subject" and r["drafter"] == drafter
                and not CHORE.match(subj) and subj.lower() not in seen):
            seen.add(subj.lower())
            revs.append(r)
    revs.sort(key=lambda r: r["created"])
    used_titles, used_revs = spread(titles, n_titles), spread(revs, n_revs)
    out = [HEADER, f"# {title}\n\n",
           "Merged PR titles become the squash commit subject, so they follow the standalone convention.\n\n"]
    for r in used_titles:
        out.append(f"- `{r['final']}`\n")
    out.append("\nRevision commits after the first on a PR, intermediate work:\n\n")
    for r in used_revs:
        out.append(f"- `{r['final']}`\n")
    return "".join(out), len(titles) + len(revs), used_titles + used_revs


def write(path, text):
    path.parent.mkdir(exist_ok=True)
    path.write_text(text)


def main():
    public = [r for r in read_jsonl(DATA / "pairs.jsonl") if r["public"]]
    people = [l.split("\t") for l in (DATA / "people.tsv").read_text().splitlines()]
    extra = ROOT / "scrub.txt"
    people += [(l, "") for l in (extra.read_text().split() if extra.exists() else [])]
    scrub = scrubber(people, " ".join(f"{r['title']} {r['draft'] or ''} {r['final']}" for r in public))
    pairs = [r for r in public if r["era"] == "agent"]
    own = [r for r in public if r["era"] == "pre-agent" and r["drafter"] == "self"]
    index = []
    for rel, fn, recs in [
        ("github/examples/pr-descriptions.md", pr_descriptions, pairs),
        ("github/examples/commit-messages.md", commit_messages, pairs),
        ("release/examples/release-notes.md", release_notes, pairs),
        ("github/examples/own-pr-descriptions.md", own_descriptions, own),
        ("github/examples/own-commit-messages.md",
         lambda r: commit_messages(r, 40, 40, "self", "Commit messages I wrote before using agents"), own),
    ]:
        text, total, used = fn(recs)
        write(SKILLS / rel, scrub(text))
        index += [f"{rel}\t{r['url']}\t{r['title']}\n" for r in used]
        print(f"  {rel}: from {total} candidates", file=sys.stderr)
    (DATA / "examples.tsv").write_text("".join(index))


if __name__ == "__main__":
    main()
